import { spawn } from 'node:child_process';
import { mkdtemp, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
const smtpEnvFile = resolve(process.env.SKY_PHP_ENV_FILE || '.env.php.local');
if (existsSync(smtpEnvFile)) process.loadEnvFile(smtpEnvFile);
const smtpKeys = ['SMTP_HOST','SMTP_PORT','SMTP_ENCRYPTION','SMTP_USERNAME','SMTP_PASSWORD','SMTP_FROM','SKY_INQUIRY_RECIPIENT'];
const missing = smtpKeys.filter(key => !process.env[key]);
if (missing.length) console.warn('[SKY GROUP][PHP] Configuración SMTP incompleta. Variables pendientes:', missing.join(', '));
// Development only. No fake success and no SMTP production defaults.
const stateDir=process.env.SKY_INQUIRY_STATE_DIR || await mkdtemp(join(tmpdir(),'skygroup-php-dev-'));
await mkdir(stateDir,{recursive:true,mode:0o700});
const port=process.env.SKY_PHP_DEV_PORT || '8085';
if(!/^\d{4,5}$/.test(port))throw new Error('Invalid development port');
const env={...process.env,SKY_INQUIRY_STATE_DIR:stateDir,SKY_INQUIRY_SECRET:process.env.SKY_INQUIRY_SECRET||randomBytes(32).toString('hex'),SKY_INQUIRY_ORIGINS:process.env.SKY_INQUIRY_ORIGINS||'http://127.0.0.1:5174,http://localhost:5174,http://127.0.0.1:5173,http://localhost:5173'};
console.log('PHP development endpoint: http://127.0.0.1:'+port+'/aircraft-inquiry.php');
console.log('SMTP is configured only through PHP environment variables. Without configuration, valid requests fail safely with HTTP 503.');
const php=spawn('php',['-S','127.0.0.1:'+port,'-t',resolve('public')],{env,stdio:'inherit'});
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>php.kill(signal));
php.on('exit',code=>{process.exitCode=code??0;});
